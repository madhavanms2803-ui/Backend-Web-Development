require('dotenv').config();
const express = require('express');
const routes = require('./routes/authRoutes');
const { AppError } = require('./services/authService');
const app = express();
app.use(express.json());
app.use('/auth', routes);
app.use((req,res) => res.status(404).json({error:{code:'NOT_FOUND',message:'Route not found'}}));
app.use((err,req,res,next) => { if (err instanceof SyntaxError && err.status === 400 && 'body' in err) return res.status(400).json({error:{code:'INVALID_JSON',message:'Request body must be valid JSON'}}); if (err instanceof AppError) return res.status(err.status).json({error:{code:err.code,message:err.message}}); return res.status(500).json({error:{code:'INTERNAL_ERROR',message:'Internal server error'}}); });
const port = Number(process.env.PORT || 3000);
if (require.main === module) app.listen(port, () => console.log('API listening on ' + port));
module.exports = app;
